    a = sl.shapes.add_shape(MSO_SHAPE.RIGHT_ARROW, Inches(x), Inches(y), Inches(0.35), Inches(0.4))
    a.fill.solid(); a.fill.fore_color.rgb = MOSS; a.line.fill.background()


