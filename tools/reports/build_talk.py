    prompts, cmds = AP.load()
    log = AP.git_log()
    d = Deck("TODAK · AI와 함께 만든 스마트팜  |  양지원")

    # 1 표지
    sl = d.slide("", dark=True, notes=(
        "안녕하세요, 2402180 양지원입니다. 저는 방울토마토 스마트팜 과제를 생성형 AI의 도움을 받아 짧은 시간 안에 만들었습니다. "
        "오늘은 무엇을 만들었는지 짧게 보여 드리고, AI를 쓰면서 느낀 점을 중심으로 말씀드리겠습니다."))
    todak_logo(sl, 0.8, 1.05, 0.9)
    d.text(sl, 0.8, 2.1, 11.5, 1.2, "AI와 함께 만든 스마트팜", 44, True, WHITE)
    d.text(sl, 0.8, 3.35, 11.5, 0.8, "짧은 시간 안에 AI의 도움을 받으며 느낀 점", 24, False, MOSS)
    d.text(sl, 0.8, 4.4, 11.5, 0.5, "TODAK 방울토마토 스마트 농업 정보시스템 · 데이터 기획 및 분석 중간고사 대체과제", 15, False, MOSS)
