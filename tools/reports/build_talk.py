            ("모르는 것을 바로 배움", "\"너가 그려준건 뭐야 개발 계획서야? 아님 다이어그램의 한 종류야?\" — 시퀀스 다이어그램·테이블 정의서를 묻고 예시로 바로 이해했다."),
